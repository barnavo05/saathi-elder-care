/**
 * Plain text summary a family member can send to the doctor.
 * Pure function so it is easy to test.
 */

import { fmt, toMin, dosesFor, doseStatus } from "./schedule.js";
import { describeSupply } from "./refill.js";

/**
 * @param {import("./types.js").ViewContext} ctx
 * @param {{avg:number,taken:number,total:number}} week
 * @param {Array<{med:object,days:number}>} low
 */
export function buildDoctorSummary(ctx, week, low) {
  const doses = dosesFor(ctx.meds, ctx.today);
  const missed = doses.filter((d) => doseStatus(d, ctx.today, ctx.taken, ctx.today, ctx.now) === "missed");
  const lines = [
    `Medication summary for ${ctx.person}`,
    "",
    "Current medicines:",
    ...ctx.meds.map((m) => `- ${m.name} ${m.dose}, ${m.times.map((t) => fmt(toMin(t))).join(" and ")}${m.note ? ` (${m.note})` : ""}`),
    "",
    `Adherence over the last 7 days: ${week.avg} percent (${week.taken} of ${week.total} doses).`,
    missed.length
      ? `Missed today so far: ${missed.map((d) => `${d.med.name} at ${fmt(d.min)}`).join(", ")}.`
      : "No missed doses today so far.",
  ];
  if (low.length) lines.push(`Running low: ${low.map(describeSupply).join("; ")}.`);
  lines.push("", "Generated by Saathi. This is a log of what was recorded, not medical advice.");
  return lines.join("\n");
}
